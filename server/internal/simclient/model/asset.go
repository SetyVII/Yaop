// Asset represents stored metadata for a binary media blob.
type Asset struct {
	ID              string  `json:"id"`
	ObjectID        string  `json:"object_id,omitempty"`
	Name            string  `json:"name"`
	MIME            string  `json:"mime"`
	Size            int64   `json:"size"`
	CreatedAt       string  `json:"created_at"`
	MediaObjectID   string  `json:"media_object_id,omitempty"`
	DurationSeconds int     `json:"duration_seconds,omitempty"`
	IsPinned        bool    `json:"is_pinned,omitempty"`
	MediaObject     *Object `json:"media_object,omitempty"`
}

var autoGeneratedMediaPatterns = []*regexp.Regexp{
	regexp.MustCompile(`^\d+$`),
	regexp.MustCompile(`(?i)^(IMG|PXL|Screenshot|VID|AUD|REC|PTT|VN|voice|audio|recording)[_-]?\d+.*`),
	regexp.MustCompile(`(?i)^.*\.(jpg|jpeg|png|webp|gif|bmp|heic|heif|m4a|mp3|wav|ogg|aac|flac|opus|amr|mp4)$`),
	regexp.MustCompile(`(?i)^(Audio recording|Grabación de audio)\s*\(.*\)$`),
}

// IsAutoGeneratedMediaTitle returns true if the title looks like an auto-generated
// filename, camera snapshot or timestamp, meaning a user-assigned title should win.
func IsAutoGeneratedMediaTitle(title, assetID, fileName string) bool {
	plain := strings.TrimSpace(title)
	if plain == "" ||
		strings.EqualFold(plain, "Untitled") ||
		strings.EqualFold(plain, "Untitled object") ||
		strings.EqualFold(plain, "Título") ||
		strings.EqualFold(plain, "Sin título") ||
		strings.EqualFold(plain, assetID) {
		return true
	}

	cleanFile := strings.TrimSpace(fileName)
	if cleanFile != "" {
		if strings.EqualFold(plain, cleanFile) {
			return true
		}
		nameWithoutExt := strings.TrimSpace(strings.TrimSuffix(cleanFile, filepath.Ext(cleanFile)))
		if strings.EqualFold(plain, nameWithoutExt) {
			return true
		}
	}

	for _, re := range autoGeneratedMediaPatterns {
		if re.MatchString(plain) {
			return true
		}
	}

	return false
}

// MediaTypeIdForFilename returns the canonical type ID and MIME for a filename extension.
func MediaTypeIdForFilename(filename string) (typeID string, mimeType string) {
	ext := strings.ToLower(filepath.Ext(filename))
	switch ext {
	case ".mp3":
		return CanonicalTypeAudio, "audio/mpeg"
	case ".wav":
		return CanonicalTypeAudio, "audio/wav"
	case ".m4a":
		return CanonicalTypeAudio, "audio/mp4"
	case ".ogg", ".opus":
		return CanonicalTypeAudio, "audio/ogg"
	case ".flac":
		return CanonicalTypeAudio, "audio/flac"
	case ".aac":
		return CanonicalTypeAudio, "audio/aac"
	case ".jpg", ".jpeg":
		return CanonicalTypeImage, "image/jpeg"
	case ".png":
		return CanonicalTypeImage, "image/png"
	case ".webp":
		return CanonicalTypeImage, "image/webp"
	case ".gif":
		return CanonicalTypeImage, "image/gif"
	case ".pdf":
		return CanonicalTypePdf, "application/pdf"
	default:
		return "", ""
	}
}

// MediaTypeIdForMime returns the canonical YAOP type ID for a media MIME type.
func MediaTypeIdForMime(mime string) string {
	m := strings.ToLower(strings.TrimSpace(mime))
	switch {
	case strings.HasPrefix(m, "image/"):
		return CanonicalTypeImage
	case m == "application/pdf":
		return CanonicalTypePdf
	case strings.HasPrefix(m, "audio/"):
		return CanonicalTypeAudio
	default:
		return ""
	}
}

// DefaultIconForMediaType returns the canonical icon and emoji for a media object.
func DefaultIconForMediaType(typeID string) *ObjectIcon {
	switch typeID {
	case CanonicalTypeImage:
		return &ObjectIcon{Emoji: "🖼️", IconName: "image-x-generic"}
	case CanonicalTypeAudio:
		return &ObjectIcon{Emoji: "🎙️", IconName: "music"}
	case CanonicalTypePdf:
		return &ObjectIcon{Emoji: "📄", IconName: "application-pdf"}
	default:
		return nil
	}
}

func NowUTC() string {
	return time.Now().UTC().Format(time.RFC3339Nano)
}
